angka_1 = 10
angka_2 = 5

# Lebih dari (>)
print(f"Apakah {angka_1} > {angka_2} = {angka_1 > angka_2}")

# Kurang dari (<)
print(f"Apakah {angka_1} < {angka_2} = {angka_1 < angka_2}")

# Lebih dari (>=)
angka_3 = 10
print(f"Apakah {angka_1} > {angka_3} = {angka_1 > angka_3}")
print(f"Apakah {angka_1} >= {angka_3} = {angka_1 >= angka_3}")

# Lebih dari (<=)
print(f"Apakah {angka_1} < {angka_3} = {angka_1 < angka_3}")
print(f"Apakah {angka_1} <= {angka_3} = {angka_1 <= angka_3}")

# sama dengan (==)
angka_4 = 100
angka_5 = 50

# angka_4 = angka_5
print(f"Apakah {angka_4} == {angka_5} = {angka_4 == angka_5}")

# tidak sama dengan (!=)
print(f"Apakah {angka_4} != {angka_5} = {angka_4 != angka_5}")